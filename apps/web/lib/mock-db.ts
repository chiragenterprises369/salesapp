/**
 * Shared in-browser mock database for the flexible data layer and Industry Packs (Wave 1 mocks).
 * OWNER: orchestrator. One store so Settings edits (fields, stages, labels, packs) show up on the
 * Board, lead detail, records pages and navigation. Persisted in localStorage (`vistar.mock.db.v2`).
 * The state shape IS the pack planner's WorkspacePackState, so mock installs use the real planner.
 *
 * v2 (dummy data seed): adds `seed` (what was generated), sample records for every custom object that
 * exists when the store is created or upgraded (and for objects installed by packs later), and
 * `notificationsRead`. A v1 store is upgraded in place on first read: every v1 edit (fields, stages,
 * labels, packs, roles, records, logs) is kept. Leads, tasks, calls, chats and the rest of the dummy
 * data are generated by lib/world from deterministic fixtures, so they never need storage.
 */
export interface MockPackRow {
  key: string;
  status: WorkspacePackStatus | 'not_installed';
  installedVersion: string | null;
  modes: string[];
  installedAt: string | null;
  lastError: string | null;
  override: PackOverride | null;
}

export interface MockDbSeed {
  version: 2;
  seededAt: string;
  /** Leads the world generates (MOCK_LEAD_COUNT). */
  leadCount: number;
  /** Objects that already received sample records (never seeded twice). */
  objects: string[];
  /** Set when the store came from a v1 upgrade. */
  upgradedFrom: 1 | null;
}

export interface MockDbData {
  v: 2;
  state: WorkspacePackState;
  /** createdAt / archivedAt per row id (fields, objects, pipelines, stages, roles). */
  meta: Record<string, { createdAt: string; archivedAt: string | null }>;
  records: CustomRecord[];
  packs: MockPackRow[];
  logs: PackInstallLog[];
  /** Super Admin registry mock: plans per pack + add-on price. */
  registry: Record<string, { plans: Plan[]; priceInrMonthly: number | null }>;
  seed: MockDbSeed;
  /** Notification ids each user marked as read (the notifications come from lib/world). */
  notificationsRead: Record<string, string[]>;
}

type MockDbV1 = Omit<MockDbData, 'v' | 'seed' | 'notificationsRead'> & { v: 1 };

const KEY = 'vistar.mock.db.v2';
const KEY_V1 = 'vistar.mock.db.v1';
const CREATED = '2026-10-01T09:00:00.000Z';

export const mockId = () => crypto.randomUUID();

function seedV1(): MockDbV1 {
  const p = mockPipeline();
  const state = emptyPackState();
  state.pipelines.push({
    id: p.id,
    key: p.key,
    name: p.name,
    isDefault: true,
    packKey: p.packKey,
    archived: false,
    stages: p.stages.map((s) => ({ id: s.id, key: s.key, name: s.name, type: s.type, probability: s.probability, color: s.color, order: s.order, archived: false, leadCount: 0 })),
  });
  state.templates.push(...WHATSAPP_TEMPLATE_FIXTURES.map((t, i) => ({ id: `0190f5a0-0000-7000-8000-7000000000${String(i).padStart(2, '0')}`, name: t.name, language: 'en', packKey: GENERIC_SALES_MANIFEST.key })));
  state.roles.push(
    ...ROLE_KINDS.map((kind, i) => ({
      id: `0190f5a0-0000-7000-8000-3000000000${String(i).padStart(2, '0')}`,
      key: SYSTEM_ROLE_KEYS[kind],
      name: ROLE_KIND_LABELS[kind],
      kind,
      dataScope: DEFAULT_ROLE_SCOPE[kind],
      permissions: [...DEFAULT_ROLE_PERMISSIONS[kind]],
      isSystem: true,
      packKey: null,
      archived: false,
    })),
  );
  // Same path as an existing workspace after migration + `pnpm packs:sync`.
  const ops = planPackInstall(state, GENERIC_SALES_MANIFEST, { modes: [] });
  const installed = applyPlanToState(state, ops, GENERIC_SALES_MANIFEST.key, mockId);
  return {
    v: 1,
    state: installed,
    meta: {},
    records: [],
    packs: [{ key: GENERIC_SALES_MANIFEST.key, status: 'active', installedVersion: GENERIC_SALES_MANIFEST.version, modes: [], installedAt: CREATED, lastError: null, override: null }],
    logs: [],
    registry: { [GENERIC_SALES_MANIFEST.key]: { plans: ['free', 'starter', 'growth', 'enterprise'], priceInrMonthly: null } },
  };
}

/** v1 -> v2: keep everything the user changed, add the v2 seed content. */
export function upgradeMockDb(v1: MockDbV1, upgradedFrom: 1 | null = 1): MockDbData {
  const db: MockDbData = {
    ...v1,
    v: 2,
    seed: { version: 2, seededAt: new Date().toISOString(), leadCount: MOCK_LEAD_COUNT, objects: [], upgradedFrom },
    notificationsRead: {},
  };
  // Sample records for every object that exists now (user-made or from a pack).
  seedObjects(db, () => true);
  return db;
}

function seed(): MockDbData {
  return syncMeta(upgradeMockDb(seedV1(), null), CREATED);
}

/** Add sample records to objects that have not been seeded yet (and match `which`). */
function seedObjects(db: MockDbData, which: (o: WorkspacePackState['objects'][number]) => boolean): void {
  for (const o of db.state.objects) {
    if (o.archived || db.seed.objects.includes(o.key) || !which(o)) continue;
    const defs = db.state.fields
      .filter((f) => f.target === `object:${o.key}` && !f.archived)
      .map((f) => ({ key: f.key, label: f.label, type: f.type, config: f.config, required: f.required, unique: f.unique, access: f.access, archivedAt: null }));
    const existing = db.records.filter((r) => r.objectKey === o.key);
    db.records.push(...seedRecordsFor(o.key, o.primaryFieldKey, defs, existing, (d, values) => validateCustomValues(d, values, { mode: 'create', roleKey: null, pathPrefix: 'values' })));
    db.seed.objects.push(o.key);
  }
}

/** Keep createdAt / archivedAt in step with the planner's `archived` flags. */
function syncMeta(db: MockDbData, now = new Date().toISOString()): MockDbData {
  const rows: Array<{ id: string; archived: boolean }> = [
    ...db.state.objects,
    ...db.state.fields,
    ...db.state.roles,
    ...db.state.pipelines,
    ...db.state.pipelines.flatMap((p) => p.stages),
  ];
  for (const r of rows) {
    const m = db.meta[r.id] ?? { createdAt: now, archivedAt: null };
    m.archivedAt = r.archived ? (m.archivedAt ?? now) : null;
    db.meta[r.id] = m;
  }
  return db;
}

let cache: MockDbData | null = null;
const listeners = new Set<() => void>();

function persist(db: MockDbData): void {
  if (typeof window === 'undefined') return;
  try {
    window.localStorage.setItem(KEY, JSON.stringify(db));
  } catch {
    // quota exceeded: keep in memory
  }
}

function load(): MockDbData | null {
  try {
    const raw = window.localStorage.getItem(KEY);
    if (raw) {
      const parsed = JSON.parse(raw) as MockDbData;
      if (parsed?.v === 2) return { ...parsed, notificationsRead: parsed.notificationsRead ?? {} };
    }
    // Browsers that still have the v1 store: upgrade once, keep the v1 key as a backup.
    const legacy = window.localStorage.getItem(KEY_V1);
    if (legacy) {
      const parsed = JSON.parse(legacy) as MockDbV1;
      if (parsed?.v === 1) {
        const upgraded = syncMeta(upgradeMockDb(parsed));
        persist(upgraded);
        return upgraded;
      }
    }
  } catch {
    // corrupted storage: fall back to the seed
  }
  return null;
}

export function readMockDb(): MockDbData {
  noteMockUse('mock-db');
  if (cache) return cache;
  if (typeof window !== 'undefined') {
    const stored = load();
    if (stored) return (cache = stored);
  }
  return (cache = seed());
}

/** Apply a change (on a deep copy), persist, notify subscribers. Returns the new data. */
export function updateMockDb(fn: (db: MockDbData) => void): MockDbData {
  const next = structuredClone(readMockDb());
  fn(next);
  // Objects that a pack just installed get sample records (objects made by hand stay empty).
  seedObjects(next, (o) => o.packKey !== null);
  cache = syncMeta(next);
  persist(cache);
  for (const l of listeners) l();
  return cache;
}

export function subscribeMockDb(listener: () => void): () => void {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

/** Back to the seed (dev tools, tests). */
export function resetMockDb(): void {
  cache = null;
  if (typeof window !== 'undefined') {
    window.localStorage.removeItem(KEY);
    window.localStorage.removeItem(KEY_V1);
  }
  updateMockDb(() => undefined);
}
